shiny::testServer(app_env$server, {
  session$setInputs(dataset = "New Zealand", csvFormat = "samples", confirmImportBtn = 0,
                    undoDataBtn = 0, importAction = "append", duplicateAction = "skip")
  original <- data.frame(soil = "Existing", sand = 50, silt = 25, clay = 25)
  change_samples(original, "Initial")
  csv_duplicates <- tempfile(fileext = ".csv")
  incoming <- data.frame(soil = c(" Existing ", "New", "New", "Existing"),
                         sand = c(50, 90, 90, 40), silt = c(25, 5, 5, 30), clay = c(25, 5, 5, 30))
  write.csv(incoming, csv_duplicates, row.names = FALSE)
  session$setInputs(fileUpload = list(datapath = csv_duplicates))
  stopifnot(identical(upload_duplicates(), c(TRUE, FALSE, TRUE, FALSE)),
            grepl("2 duplicate row(s). 2 row(s)", output$uploadDuplicateSummary, fixed = TRUE))
  session$setInputs(confirmImportBtn = 1)
  stopifnot(nrow(soil_data()) == 3L, identical(soil_data()$sand, c(50, 90, 40)))
  session$setInputs(undoDataBtn = 1)
  stopifnot(identical(soil_data(), original))
  session$setInputs(fileUpload = list(datapath = csv_duplicates), importAction = "replace")
  stopifnot(identical(upload_duplicates(), c(FALSE, FALSE, TRUE, FALSE)))
  session$setInputs(confirmImportBtn = 2)
  stopifnot(nrow(soil_data()) == 3L)
  session$setInputs(undoDataBtn = 2)
  session$setInputs(fileUpload = list(datapath = csv_duplicates), importAction = "append", duplicateAction = "keep")
  session$setInputs(confirmImportBtn = 3)
  stopifnot(nrow(soil_data()) == 5L)
  session$setInputs(undoDataBtn = 3)
  write.csv(original, csv_duplicates, row.names = FALSE)
  previous <- undo_state()
  session$setInputs(fileUpload = list(datapath = csv_duplicates), duplicateAction = "skip")
  session$setInputs(confirmImportBtn = 4)
  stopifnot(identical(soil_data(), original), identical(undo_state(), previous),
            grepl("No samples added", sample_feedback(), fixed = TRUE))
  # A workspace change during preview must be included in duplicate detection.
  session$setInputs(fileUpload = list(datapath = csv_duplicates))
  change_samples(original[FALSE, ], "Cleared")
  stopifnot(!any(upload_duplicates()))
  session$setInputs(confirmImportBtn = 5)
  stopifnot(nrow(soil_data()) == 1L)
  unlink(csv_duplicates)
})
cat("CSV duplicates: append, replace, explicit keep, trimmed names, undo, no-op and live workspace changes PASS\n")
