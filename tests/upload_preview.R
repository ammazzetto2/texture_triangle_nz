expect_error <- function(expr) stopifnot(inherits(tryCatch({force(expr); NULL}, error = identity), "error"))
raw <- data.frame(ID = c("001", "NA", "", "Bad", "Rounded"), SAND = c("50", "90", "abc", "110", "33.3"),
                  Silt = c("25", "5", "20", "-5", "33.3"), Clay = c("25", "5", "80", "-5", "33.3"),
                  Notes = "discard", check.names = FALSE)
mapping <- c(soil = "ID", sand = "SAND", silt = "Silt", clay = "Clay")
inspection <- app_env$inspect_upload(raw, mapping)
stopifnot(identical(unique(inspection$issues$row), 3:5), inspection$samples$soil[1] == "001",
          inspection$samples$soil[2] == "NA", inspection$ignored == "Notes",
          any(inspection$issues$field == "total"))
expect_error(app_env$inspect_upload(raw, c(soil = "ID", sand = "SAND", silt = "SAND", clay = "Clay")))
stopifnot(abs(app_env$remaining_percentage(c(sand = 33.3, silt = 33.3, clay = NA_real_), "clay") - 33.4) < 1e-10)
expect_error(app_env$remaining_percentage(c(sand = 80, silt = 30, clay = 0), "clay"))
expect_error(app_env$remaining_percentage(c(sand = NA_real_, silt = 30, clay = 0), "clay"))
csv <- tempfile(fileext = ".csv")
writeLines(c("soil,sand,silt,clay", "Wrong,one,50,25,25"), csv)
expect_error(app_env$read_upload_table(csv))
write.csv(data.frame(soil = "Two\nlines", sand = 50, silt = 25, clay = 25), csv, row.names = FALSE)
stopifnot(nrow(app_env$read_upload_table(csv)) == 1L)
